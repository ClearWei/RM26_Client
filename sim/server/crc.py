def get_crc8_check_sum(message, length, crc8):
    for i in range(length):
        index = crc8 ^ message[i]
        crc8 = CRC8_TAB[index]
    return crc8

def append_crc8_check_sum(message):
    """
    将 CRC8 校验值追加到字节数组末尾。
    """
    crc8 = 0xff
    length = len(message)
    # 该接口直接追加校验字节，调用方不需要预留空间。
    crc8 = get_crc8_check_sum(message, length, crc8)
    message.append(crc8)

def get_crc16_check_sum(message, length, crc16):
    for i in range(length):
        byte = message[i]
        crc16 = ((crc16 >> 8) ^ CRC16_TAB[(crc16 ^ byte) & 0x00ff]) & 0xFFFF
    return crc16

def append_crc16_check_sum(message):
    """
    将 CRC16 校验值追加到字节数组末尾。
    """
    crc16 = 0xffff
    length = len(message)
    crc16 = get_crc16_check_sum(message, length, crc16)
    message.append(crc16 & 0x00ff)
    message.append((crc16 >> 8) & 0x00ff)
